library(phyloseq)
library(dplyr)
library(readr)
library(ggplot2)
library(patchwork)
library(scales)

# ------------------------------------------------------------
# 1. Input files
# ------------------------------------------------------------

GENUS_TSV <- "genus_table_export/genus_table.tsv"
META_TSV <- "metadata.tsv"

# Saved models were generated by the original psychometric
# ANCOM-BC2 analysis.
fit_ace <- readRDS(
  "psychometric_analysis/psychometric_taxa_ancombc/ancombc2_psych_ace_tot.rds"
)
fit_drsp <- readRDS(
  "psychometric_analysis/psychometric_taxa_ancombc/ancombc2_psych_PMDD_drsp_mood.rds"
)

# ------------------------------------------------------------
# 2. Import genus-level count table
# ------------------------------------------------------------

otu_genus <- read.delim(
  GENUS_TSV,
  skip = 1,
  row.names = 1,
  check.names = FALSE,
  comment.char = ""
)

if ("taxonomy" %in% colnames(otu_genus)) {
  otu_genus$taxonomy <- NULL
}

otu_genus <- as.matrix(otu_genus)
storage.mode(otu_genus) <- "numeric"

# ------------------------------------------------------------
# 3. Import and prepare study metadata
# ------------------------------------------------------------

md <- read.delim(
  META_TSV,
  header = TRUE,
  sep = "\t",
  check.names = FALSE,
  stringsAsFactors = FALSE
)

if ("#SampleID" %in% names(md) && !"sample-id" %in% names(md)) {
  names(md)[names(md) == "#SampleID"] <- "sample-id"
}

md <- md |>
  mutate(
    PMDD = factor(
      as.character(PMDD),
      levels = c("0", "2"),
      labels = c("Control", "PMDD")
    ),
    Phase = factor(as.character(Phase), levels = c("F", "L")),
    enrollment_id = factor(enrollment_id)
  )

# Raw-scale psychometric values used on figure x-axes.
md_raw <- read_tsv(META_TSV, show_col_types = FALSE)

if ("#SampleID" %in% names(md_raw) &&
    !"sample-id" %in% names(md_raw)) {
  md_raw <- rename(md_raw, `sample-id` = `#SampleID`)
}

required_md <- c("sample-id", "enrollment_id", "PMDD",
                 "ace_tot", "drsp_mood")
stopifnot(all(required_md %in% names(md_raw)))

md_raw <- md_raw |>
  mutate(
    `sample-id` = as.character(`sample-id`),
    PMDD = case_when(
      as.character(PMDD) %in% c("0", "C", "Control") ~ "Control",
      as.character(PMDD) %in% c("2", "P", "PMDD") ~ "PMDD",
      TRUE ~ NA_character_
    ),
    PMDD = factor(PMDD, levels = c("Control", "PMDD")),
    enrollment_id = factor(enrollment_id),
    ace_tot = as.numeric(ace_tot),
    drsp_mood = as.numeric(drsp_mood)
  )

if (anyDuplicated(md$`sample-id`) ||
    anyDuplicated(md_raw$`sample-id`)) {
  stop("Duplicate sample IDs detected in metadata.")
}

# ------------------------------------------------------------
# 4. Match samples and construct phyloseq
# ------------------------------------------------------------

study_ids <- md$`sample-id`

if (!all(study_ids %in% colnames(otu_genus))) {
  stop("Some study sample IDs are absent from the genus count table.")
}

otu_genus <- otu_genus[, study_ids, drop = FALSE]

md_ps <- as.data.frame(md)
rownames(md_ps) <- md_ps$`sample-id`

tax_genus <- matrix(
  rownames(otu_genus),
  ncol = 1,
  dimnames = list(rownames(otu_genus), "Genus")
)

ps_all <- phyloseq(
  otu_table(otu_genus, taxa_are_rows = TRUE),
  sample_data(md_ps),
  tax_table(tax_genus)
)

# ------------------------------------------------------------
# 5. Identify taxa and verify saved model data
# ------------------------------------------------------------

match_genus <- function(ids, genus) {
  # Prefer genus-level names in GTDB-style taxonomy strings.
  matches <- ids[
    grepl(paste0("(^|;)g__", genus, "($|;)"),
          ids, ignore.case = TRUE)
  ]
  if (!length(matches)) {
    matches <- ids[tolower(ids) == tolower(genus)]
  }
  matches
}

stopifnot(
  !is.null(fit_ace$bias_correct_log_table),
  !is.null(fit_drsp$bias_correct_log_table)
)

# ------------------------------------------------------------
# 6. SFMI01 x ACE: bias-corrected data and direction check
# ------------------------------------------------------------

ace_mat <- as.matrix(fit_ace$bias_correct_log_table)
sfmi_row <- match_genus(rownames(ace_mat), "SFMI01")
if (length(sfmi_row) != 1L) {
  stop("Expected exactly one SFMI01 genus in ACE bias-corrected table; found ",
       length(sfmi_row), ". Matches: ", paste(sfmi_row, collapse = " | "))
}
sfmi_bc_df <- data.frame(
  `sample-id` = colnames(ace_mat),
  SFMI01_bc = as.numeric(ace_mat[sfmi_row, ]),
  check.names = FALSE
) |>
  left_join(md_raw |> select(all_of(required_md)), by = "sample-id")
if (anyNA(sfmi_bc_df$enrollment_id)) warning("ACE table contains sample IDs missing from metadata")

sfmi_bc_lm <- lm(SFMI01_bc ~ ace_tot, data = sfmi_bc_df)
sfmi_plot_slope <- unname(coef(sfmi_bc_lm)["ace_tot"])
ace_res <- as.data.frame(fit_ace$res)
if (!"taxon" %in% names(ace_res)) {
  if (!is.null(rownames(ace_res))) ace_res$taxon <- rownames(ace_res)
}
sfmi_ancom <- ace_res |>
  filter(taxon == sfmi_row) |>
  select(any_of(c("taxon", "lfc_ace_tot", "p_ace_tot", "q_ace_tot")))
if (nrow(sfmi_ancom) != 1L || !"lfc_ace_tot" %in% names(sfmi_ancom)) {
  stop("Could not identify unique SFMI01 ACE coefficient in fit_ace$res")
}
sfmi_ancom_lfc <- sfmi_ancom$lfc_ace_tot[[1]]
sfmi_check <- data.frame(
  taxon = sfmi_row,
  n_plotted = sum(complete.cases(sfmi_bc_df[, c("SFMI01_bc", "ace_tot")])),
  ANCOM_BC2_ACE_LFC = sfmi_ancom_lfc,
  descriptive_LM_ACE_slope = sfmi_plot_slope,
  same_sign = sign(sfmi_ancom_lfc) == sign(sfmi_plot_slope)
)

print(sfmi_check)
if (!isTRUE(sfmi_check$same_sign)) warning("SFMI01 descriptive slope differs in sign from ANCOM-BC2")

p_sfmi <- sfmi_bc_df |>
  filter(!is.na(SFMI01_bc), !is.na(ace_tot)) |>
  ggplot(aes(x = ace_tot, y = SFMI01_bc)) +
  geom_point(size = 3, alpha = 0.8) +
  geom_smooth(method = "lm", formula = y ~ x, se = TRUE, color = "#0072B2") +
  theme_classic(base_size = 14) +
  labs(x = "ACE total score", y = "Bias-corrected log abundance", title = "SFMI01")


# ------------------------------------------------------------
# 7. GCA-900066905 x DRSP mood: all samples, including zeros
# ------------------------------------------------------------

# Identify the GCA genus; the feature may be a full taxonomy ID or a tax_table label.
feature_ids <- taxa_names(ps_all)
gca_features <- match_genus(feature_ids, "GCA-900066905")
if (!length(gca_features) && !is.null(tax_table(ps_counts, errorIfNULL = FALSE))) {
  tx <- as(tax_table(ps_counts), "matrix")
  genus_cols <- which(tolower(colnames(tx)) %in% c("genus", "g"))
  if (length(genus_cols)) {
    gca_features <- rownames(tx)[as.character(tx[, genus_cols[[1]]]) %in%
                                   c("GCA-900066905", "g__GCA-900066905")]
  } else {
    gca_features <- rownames(tx)[apply(tx, 1, function(z)
      any(grepl("(^|;)g__GCA-900066905($|;)", z, ignore.case = TRUE)))]
  }
}
if (!length(gca_features)) {
  stop("Cannot find genus GCA-900066905 in taxa names or taxonomy table. ",
       "Check the count object and taxonomy level used for ANCOM-BC2.")
}

count_mat <- as(otu_table(ps_counts), "matrix")
if (!taxa_are_rows(ps_counts)) count_mat <- t(count_mat)
if (any(count_mat < 0, na.rm = TRUE)) stop("Input OTU table has negative counts")
sample_totals <- colSums(count_mat, na.rm = FALSE)
if (any(!is.finite(sample_totals) | sample_totals <= 0)) {
  stop("Some samples have zero/invalid total counts; cannot calculate relative abundance")
}
gca_rel <- colSums(count_mat[gca_features, , drop = FALSE]) / sample_totals

gca_all_df <- data.frame(
  `sample-id` = names(gca_rel),
  GCA900066905 = as.numeric(gca_rel),
  check.names = FALSE
) |>
  left_join(md_raw |> select(all_of(required_md)), by = "sample-id") |>
  filter(!is.na(drsp_mood), !is.na(PMDD)) |>
  mutate(
    detection = if_else(GCA900066905 > 0, "Detected", "Not detected"),
    GCA_percent = GCA900066905 * 100
  )
if (anyNA(gca_all_df$GCA900066905)) stop("Missing GCA abundance values after joining")
cat("\nGCA samples plotted:", nrow(gca_all_df), "\n")
print(table(gca_all_df$PMDD, gca_all_df$detection))
}

p_gca_all <- ggplot(gca_all_df,
                    aes(x = drsp_mood, y = GCA_percent, color = PMDD)) +
  geom_point(position = position_jitter(width = 0.5, height = 0, seed = 123),
             size = 2.8, alpha = 0.75) +
  scale_y_continuous(trans = scales::pseudo_log_trans(base = 10)) +
  scale_color_manual(values = c("Control" = "#999999", "PMDD" = "#D55E00")) +
  theme_classic(base_size = 14) +
  labs(x = "DRSP mood score", y = "Relative abundance (%)",
       color = "Group", title = "GCA-900066905")

# Optional: export GCA interaction statistics from saved ANCOM-BC2 model.
drsp_res <- as.data.frame(fit_drsp$res)
if (!"taxon" %in% names(drsp_res)) drsp_res$taxon <- rownames(drsp_res)
gca_ancom_row <- match_genus(as.character(drsp_res$taxon), "GCA-900066905")
if (length(gca_ancom_row) == 1L) {
  write.csv(drsp_res[drsp_res$taxon == gca_ancom_row, , drop = FALSE],
            "CHECK_GCA_DRSP_ANCOM_statistics.csv", row.names = FALSE)
} else {
  warning("Could not uniquely identify GCA in DRSP ANCOM-BC2 results")
}


# ------------------------------------------------------------
# 8. Combine and export final two-panel figure
# ------------------------------------------------------------

p_final_taxa <- p_sfmi + p_gca_all + plot_annotation(tag_levels = "A")
print(p_final_taxa)
ggsave("Significant_taxa_psychometrics_final.pdf", p_final_taxa,
       width = 11, height = 5)
ggsave("Significant_taxa_psychometrics_final.png", p_final_taxa,
       width = 11, height = 5, dpi = 600, bg = "white")